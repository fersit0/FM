// Capturas de Hoy, Señal, Ejercicios y Ajustes con datos de prueba. Uso: node scripts/capturas-pantallas.mjs
import { chromium, devices } from 'playwright'
import { mkdirSync } from 'node:fs'
const dir = process.env.CAPTURAS_DIR ?? 'capturas'
mkdirSync(dir, { recursive: true })
const browser = await chromium.launch()
const ctx = await browser.newContext({ ...devices['iPhone 14'], viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: 'dark' })
const page = await ctx.newPage()
await page.goto('http://localhost:5173/gym-app/?seed=1')
await page.waitForTimeout(1200)
await page.evaluate(() => localStorage.removeItem('gym-app:sesion-activa'))
await page.goto('http://localhost:5173/gym-app/')
await page.waitForTimeout(900)
await page.screenshot({ path: `${dir}/hoy.png` })
await page.screenshot({ path: `${dir}/hoy-completa.png`, fullPage: true })
await page.getByRole('button', { name: 'Ajustes' }).click()
await page.waitForTimeout(600)
await page.screenshot({ path: `${dir}/ajustes.png` })
await page.keyboard.press('Escape')
await page.waitForTimeout(400)
await page.getByRole('button', { name: 'Señal' }).click()
await page.waitForTimeout(700)
await page.screenshot({ path: `${dir}/senal.png` })
await page.screenshot({ path: `${dir}/senal-completa.png`, fullPage: true })
await page.getByRole('button', { name: 'Ejercicios' }).click()
await page.waitForTimeout(700)
await page.screenshot({ path: `${dir}/ejercicios.png` })
await page.getByRole('button', { name: /Sentadilla goblet/ }).click()
await page.waitForTimeout(600)
await page.screenshot({ path: `${dir}/ejercicio-hoja.png` })
await page.keyboard.press('Escape')
// Hoy sin datos
await page.goto('http://localhost:5173/gym-app/?seed=0')
await page.waitForTimeout(1000)
await page.goto('http://localhost:5173/gym-app/')
await page.waitForTimeout(800)
await page.screenshot({ path: `${dir}/hoy-vacio.png` })
await page.getByRole('button', { name: 'Señal' }).click()
await page.waitForTimeout(600)
await page.screenshot({ path: `${dir}/senal-vacia.png` })
await browser.close()
console.log('listo:', dir)
